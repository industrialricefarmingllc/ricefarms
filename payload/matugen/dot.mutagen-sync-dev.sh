#!/bin/bash
# matugen-sync-dev.sh - push local matugen terminal palette to dev.
#
# Scope: per-connection + per-user (NOT system-wide).
#   - Files land in /home/dev/.config/matugen-sync/ and
#     /home/dev/.config/opencode/themes/ (your user only, never /etc).
#   - The remote shell applies them via OSC escape sequences, which only
#     affect the terminal emulator showing YOUR connection. Other users /
#     sessions are untouched. Hook runs only for interactive SSH shells.
# Re-run after wallpaper/theme change to refresh the snapshot.
# Modes:
#   (no args)            foreground sync, blocks (manual runs).
#   --background | --bg  quiet background sync for use by d()/ssh() wrappers
#                        and matugen-watch-dev.sh. Skips work when local
#                        outputs are not newer than the stamp, uses a flock
#                        so concurrent triggers collapse to one, uploads in
#                        a single tar pipe + single remote step (2 SSH
#                        connections total, multiplexed via ControlMaster),
#                        and applies the palette to the local terminal
#                        immediately so live changes show without reconnect.
#                        Remote opencode picks up matugen.json via the
#                        tui-matugen-live.ts watcher (poll + fs.watch), so
#                        no reconnect is needed there either.
#   --force | -f         ignore stamp check (with or without --background).
set -euo pipefail
# Guard so any interactive-shell ssh() wrapper never recurses into this script's own ssh calls.
export MATUGEN_SYNC_IN_PROGRESS=1

BACKGROUND=0
FORCE=0
for _arg in "$@"; do
  case "$_arg" in
    --background|--bg) BACKGROUND=1 ;;
    --force|-f) FORCE=1 ;;
  esac
done

SRC_KITTY="$HOME/.config/kitty/matugen-colors.conf"
SRC_OPENCODE="$HOME/.config/opencode/themes/matugen.json"
SRC_TUI_LIVE="$HOME/.config/opencode/tui-matugen-live.ts"
STAMP="$HOME/.cache/matugen-sync-dev.last"
LOCK="$HOME/.cache/matugen-sync-dev.lock"
mkdir -p "$HOME/.cache"

# Singleton: collapse concurrent background triggers (d() + watcher firing
# together, or rapid wallpaper changes) to a single run.
exec 9>"$LOCK"
if ! flock -n 9 2>/dev/null; then
  [ "$BACKGROUND" -eq 1 ] || echo "matugen: another sync in progress, skipping"
  exit 0
fi

# Fast stamp check BEFORE generating/uploading. Foreground manual runs
# without --force keep the old behaviour (always sync); background runs
# (and --force callers) skip when nothing changed so connects stay instant.
if [ "$FORCE" -eq 0 ] && [ "$BACKGROUND" -eq 1 ]; then
  if [ -f "$STAMP" ] && [ ! "$SRC_KITTY" -nt "$STAMP" ] && { [ ! -f "$SRC_OPENCODE" ] || [ ! "$SRC_OPENCODE" -nt "$STAMP" ]; } && { [ ! -f "$SRC_TUI_LIVE" ] || [ ! "$SRC_TUI_LIVE" -nt "$STAMP" ]; }; then
    exit 0
  fi
fi
OUTDIR="$(mktemp -d)"
trap 'rm -rf "$OUTDIR"' EXIT

python3 - "$SRC_KITTY" "$OUTDIR" <<'PYEOF'
import re, sys, datetime
src, outdir = sys.argv[1], sys.argv[2]
vals = {}
for line in open(src):
    m = re.match(r'^(\w+)\s+(#[0-9a-fA-F]{6})\s*$', line.strip())
    if m:
        vals[m.group(1)] = m.group(2)
need = ['background', 'foreground', 'cursor'] + [f'color{i}' for i in range(16)]
missing = [k for k in need if k not in vals]
if missing:
    sys.exit(f'missing keys in {src}: {missing}')
stamp = datetime.datetime.now().strftime('%Y-%m-%d %H:%M')
header = (f'# AUTO-GENERATED by ~/matugen-sync-dev.sh from local kitty '
          f'matugen-colors.conf ({stamp}) - do not edit.\n'
          f'# Re-run ~/matugen-sync-dev.sh locally to refresh.\n')

apply = [header + '# Applies YOUR palette to this connection\'s terminal only.\n']
apply.append('if [ -n "$TMUX" ]; then _m_tmux=1; else case "$TERM" in tmux*|screen*) _m_tmux=1;; *) _m_tmux=;; esac; fi\n')
apply.append('if [ -n "$_m_tmux" ]; then _m_pre=$(printf \'\\033Ptmux;\\033\'); _m_post=$(printf \'\\033\\\\\'); else _m_pre=\'\'; _m_post=\'\'; fi\n')
apply.append('_m_put() {\n  if [ -n "$_m_pre" ]; then printf \'%s\\033%s\\a%s\' "$_m_pre" "$1" "$_m_post"; else printf \'\\033%s\\a\' "$1"; fi\n}\n')
apply.append(f'_m_put "]11;{vals["background"]}"  # background\n')
apply.append(f'_m_put "]10;{vals["foreground"]}"  # foreground\n')
apply.append(f'_m_put "]12;{vals["cursor"]}"      # cursor\n')
for i in range(16):
    apply.append(f'_m_put "]4;{i};{vals[f"color{i}"]}"\n')
open(f'{outdir}/apply-colors.sh', 'w').write(''.join(apply))

reset_ = [header + '# Resets palette/fg/bg/cursor for this connection\'s terminal.\n']
reset_.append('if [ -n "$TMUX" ]; then _m_tmux=1; else case "$TERM" in tmux*|screen*) _m_tmux=1;; *) _m_tmux=;; esac; fi\n')
reset_.append('if [ -n "$_m_tmux" ]; then _m_pre=$(printf \'\\033Ptmux;\\033\'); _m_post=$(printf \'\\033\\\\\'); else _m_pre=\'\'; _m_post=\'\'; fi\n')
reset_.append('_m_put() {\n  if [ -n "$_m_pre" ]; then printf \'%s\\033%s\\a%s\' "$_m_pre" "$1" "$_m_post"; else printf \'\\033%s\\a\' "$1"; fi\n}\n')
for code in (']104', ']110', ']111', ']112'):
    reset_.append(f'_m_put "{code}"\n')
open(f'{outdir}/reset-colors.sh', 'w').write(''.join(reset_))

hook = '''# --- matugen-sync-dev (per-connection palette) ---
# Applies YOUR local matugen palette to this connection's terminal only (OSC
# sequences affect just the emulator showing this session). Per-user files in
# ~/.config/matugen-sync/, never system-wide. Refresh: run ~/matugen-sync-dev.sh locally.
if [[ -o interactive ]] && [ -n "$SSH_CONNECTION" ] && [[ -t 1 ]] && [ -r "$HOME/.config/matugen-sync/apply-colors.sh" ]; then
  ( . "$HOME/.config/matugen-sync/apply-colors.sh" >/dev/tty 2>/dev/null || true )
  _matugen_sync_reset() {
    [[ -t 1 ]] && [ -r "$HOME/.config/matugen-sync/reset-colors.sh" ] && ( . "$HOME/.config/matugen-sync/reset-colors.sh" >/dev/tty 2>/dev/null || true )
  }
  autoload -Uz add-zsh-hook 2>/dev/null || true
  add-zsh-hook zshexit _matugen_sync_reset 2>/dev/null || trap '_matugen_sync_reset' EXIT
fi
'''
installer = '''import shutil, time
from pathlib import Path
p = Path.home() / ".zshrc"
text = p.read_text()
marker = "# --- matugen-sync-dev (per-connection palette) ---"
hook = (Path.home() / ".config/matugen-sync/hook-block.sh").read_text()
if marker not in text:
    shutil.copy(p, f"{p}.bak.{int(time.time())}")
    p.write_text(text.rstrip("\\n") + "\\n\\n" + hook)
    print("hook installed")
else:
    print("hook already present")
'''
open(f'{outdir}/install-hook.py', 'w').write(installer)
open(f'{outdir}/hook-block.sh', 'w').write(hook)
print('generated apply/reset/hook')
PYEOF

SSH="ssh -o ConnectTimeout=10 -o BatchMode=yes"

# Immediate local apply: the generated OSC script targets the *local*
# emulator, so sourcing it now updates the current terminal even before the
# upload finishes - and, crucially, applies live theme changes to an
# already-connected session with no reconnect. Best-effort, never fails.
# SYNC_TTY is captured by the d()/ssh() wrapper before mosh takes over.
if [ -f "$OUTDIR/apply-colors.sh" ]; then
  _tty="${SYNC_TTY:-}"
  [ -z "$_tty" ] && _tty="$(tty 2>/dev/null || true)"
  if [ -n "$_tty" ] && [ -w "$_tty" ]; then
    ( sh "$OUTDIR/apply-colors.sh" >"$_tty" 2>/dev/null || true ) 2>/dev/null
  elif [ "$BACKGROUND" -eq 0 ] && [ -c /dev/tty ]; then
    # Foreground manual run with no tty (e.g. piped): try stdout's tty.
    ( sh "$OUTDIR/apply-colors.sh" >/dev/tty 2>/dev/null || true ) 2>/dev/null
  fi
  unset _tty
fi

# Stage payload with final remote-relative layout, then single-tar upload
# (1st and only bulk-transfer connection). Destinations:
#   ~/.config/matugen-sync/{apply,reset,hook-block,matugen-colors.conf}
#   ~/.config/opencode/themes/matugen.json
#   ~/.config/opencode/tui-matugen-live.ts
STAGE="$OUTDIR/stage"
mkdir -p "$STAGE/matugen-sync" "$STAGE/opencode/themes" "$STAGE/opencode"
cp "$OUTDIR/apply-colors.sh" "$OUTDIR/reset-colors.sh" "$OUTDIR/hook-block.sh" "$OUTDIR/install-hook.py" "$STAGE/matugen-sync/"
cp "$SRC_KITTY" "$STAGE/matugen-sync/matugen-colors.conf"
[ -f "$SRC_OPENCODE" ] && cp "$SRC_OPENCODE" "$STAGE/opencode/themes/matugen.json" || true
[ -f "$SRC_TUI_LIVE" ] && cp "$SRC_TUI_LIVE" "$STAGE/opencode/tui-matugen-live.ts" || true
tar -cz -C "$STAGE" . | $SSH dev 'mkdir -p ~/.config/matugen-sync ~/.config/opencode/themes && tar -xz -C ~/.config'

# Single remote step (2nd connection, multiplexed so ~50ms): mode pin +
# transparent surfaces + zshrc hook install + tui.json merge. Previously
# three separate ssh calls; now one python invocation + shell syntax check
# chained in the same connection.
cat >"$OUTDIR/remote-all.py" <<'RPYEOF'
import json, re, shutil, time
from pathlib import Path
# 1. Mode pin + transparent surfaces (must run after every theme copy).
bg = "#111418"
try:
    m = re.search(r"^background\s+(#[0-9a-fA-F]{6})",
                  (Path.home() / ".config/matugen-sync/matugen-colors.conf").read_text(), re.M)
    if m:
        bg = m.group(1)
except FileNotFoundError:
    pass
r, g, b = (int(bg[i:i + 2], 16) for i in (1, 3, 5))
intended = "light" if (0.299 * r + 0.587 * g + 0.114 * b) / 255 > 0.5 else "dark"
p = Path.home() / ".config/opencode/themes/matugen.json"
try:
    d = json.loads(p.read_text())
    for key, v in d.get("theme", {}).items():
        if isinstance(v, dict) and "dark" in v and intended in v:
            v["dark"] = v[intended]
    for key in ["background", "backgroundPanel", "backgroundElement", "diffContextBg"]:
        if key in d.get("theme", {}):
            d["theme"][key] = {"dark": "none", "light": "none"}
    p.write_text(json.dumps(d, indent=2) + "\n")
    print(f"remote theme pinned to {intended} (kitty bg {bg}), backgrounds -> transparent")
except FileNotFoundError:
    print("remote theme missing, skipping tweak")
# 2. zshrc hook install (idempotent).
zp = Path.home() / ".zshrc"
marker = "# --- matugen-sync-dev (per-connection palette) ---"
hook = (Path.home() / ".config/matugen-sync/hook-block.sh").read_text()
text = zp.read_text()
if marker not in text:
    shutil.copy(zp, f"{zp}.bak.{int(time.time())}")
    zp.write_text(text.rstrip("\n") + "\n\n" + hook)
    print("hook installed")
else:
    print("hook already present")
# 3. tui.json merge: theme=matugen + live-reload plugin (idempotent).
tp = Path.home() / ".config/opencode/tui.json"
d = json.loads(tp.read_text())
shutil.copy(tp, f"{tp}.bak.{int(time.time())}")
d["theme"] = "matugen"
pl = d.get("plugin", [])
if "./tui-matugen-live.ts" not in pl:
    pl.append("./tui-matugen-live.ts")
d["plugin"] = pl
tp.write_text(json.dumps(d, indent=2) + "\n")
print("tui theme ->", d["theme"], "plugins ->", pl)
RPYEOF
$SSH dev 'python3 && zsh -n ~/.zshrc && sh -n ~/.config/matugen-sync/apply-colors.sh && sh -n ~/.config/matugen-sync/reset-colors.sh && echo REMOTE-OK' < "$OUTDIR/remote-all.py"
mkdir -p "$HOME/.cache" && touch "$HOME/.cache/matugen-sync-dev.last"
[ "$BACKGROUND" -eq 1 ] || echo "synced. Re-run $0 after wallpaper/theme changes."
# Background callers tail the log; keep a one-line confirmation there too.
[ "$BACKGROUND" -eq 1 ] && echo "matugen: background sync done $(date '+%H:%M:%S')" || true
